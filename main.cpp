// 캐릭터 이동 함수
void na_move(int *Px,int *Py)
{
	int ui;
		ui = getch();                  

		// 사용자 입력 구분
		switch(ui)
		{
			case UP:
				//벽 통과 방지 조건.------
				if(map_0[(*Px)-1][*Py]==1)
					break;
				//-------------------------
				map_0[*Px][*Py] = 0;
				(*Px)--;
				break;
			case RIGHT:
				if(map_0[*Px][(*Py)+1]==1)
					break;
				map_0[*Px][*Py] = 0;
				(*Py)++;
				break;
			case DOWN:
				if(map_0[(*Px)+1][*Py]==1)
					break;
				map_0[*Px][*Py] = 0;
				(*Px)++;
				break;
			case LEFT:
				if(map_0[*Px][(*Py)-1]==1)
					break;
				map_0[*Px][*Py] = 0;
				(*Py)--;
				break;
			case 'p':
				exit(0); break;
		}
}

