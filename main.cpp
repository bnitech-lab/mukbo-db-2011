// 해당 위치로 커서를 이동시키는 함수
void gotoxy(int x, int y) 
{
	COORD pos = {x, y};
	SetConsoleCursorPosition(GetStdHandle(STD_OUTPUT_HANDLE), pos);
}

// 화면을 지우고 커서 위치를 0, 0위치로 이동시키는 함수
void clrscr(void)
{ 
	COORD Cur= {0, 0};
	unsigned long dwLen;
	FillConsoleOutputCharacter(GetStdHandle(STD_OUTPUT_HANDLE) , '  ', 100*25, Cur, &dwLen);
}

